-- Events are complete snapshots. Versions must increase per application across committed batches.
-- Exact retries are ignored. Conflicting retries, reused versions and late events fail atomically.
CREATE OR REPLACE PROCEDURE PROCESS_APPLICATION_EVENTS()
RETURNS VARCHAR LANGUAGE SQL EXECUTE AS CALLER AS
$$
DECLARE
  bad_count INTEGER;
  bad_event EXCEPTION (-20001, 'Conflicting, invalid, or late event. Inspect source and repair before retry.');
BEGIN
  -- DDL is outside the transaction because Snowflake DDL implicitly commits.
  CREATE OR REPLACE TEMPORARY TABLE EVENT_BATCH LIKE APPLICATION_EVENTS;
  CREATE OR REPLACE TEMPORARY TABLE NEW_EVENTS LIKE APPLICATION_EVENTS;
  BEGIN TRANSACTION;
  INSERT INTO EVENT_BATCH SELECT * FROM APPLICATION_EVENT_STREAM;
  SELECT COUNT(*) INTO :bad_count FROM EVENT_BATCH
    WHERE SOURCE_VERSION < 1 OR EVENT_ID IS NULL OR APPLICATION_ID IS NULL OR EVENT_AT IS NULL;
  IF (bad_count > 0) THEN RAISE bad_event; END IF;
  SELECT COUNT(*) INTO :bad_count FROM (
    SELECT EVENT_ID FROM EVENT_BATCH GROUP BY EVENT_ID
    HAVING COUNT(DISTINCT TO_JSON(ARRAY_CONSTRUCT(APPLICATION_ID, SOURCE_VERSION, EVENT_AT,
      DECISION, RISK_CLASS, CHANNEL))) > 1
  );
  IF (bad_count > 0) THEN RAISE bad_event; END IF;
  SELECT COUNT(*) INTO :bad_count FROM EVENT_BATCH B JOIN PROCESSED_EVENTS P USING (EVENT_ID)
    WHERE TO_JSON(ARRAY_CONSTRUCT(B.APPLICATION_ID,B.SOURCE_VERSION,B.EVENT_AT,B.DECISION,B.RISK_CLASS,B.CHANNEL))
      <> TO_JSON(ARRAY_CONSTRUCT(P.APPLICATION_ID,P.SOURCE_VERSION,P.EVENT_AT,P.DECISION,P.RISK_CLASS,P.CHANNEL));
  IF (bad_count > 0) THEN RAISE bad_event; END IF;
  INSERT INTO NEW_EVENTS
    SELECT B.* FROM EVENT_BATCH B WHERE NOT EXISTS (
      SELECT 1 FROM PROCESSED_EVENTS P WHERE P.EVENT_ID = B.EVENT_ID)
    QUALIFY ROW_NUMBER() OVER (PARTITION BY EVENT_ID ORDER BY EVENT_AT) = 1;
  SELECT COUNT(*) INTO :bad_count FROM NEW_EVENTS N JOIN APPLICATION_CURRENT C USING (APPLICATION_ID)
    WHERE N.SOURCE_VERSION <= C.SOURCE_VERSION;
  IF (bad_count > 0) THEN RAISE bad_event; END IF;
  SELECT COUNT(*) INTO :bad_count FROM (
    SELECT APPLICATION_ID, SOURCE_VERSION FROM NEW_EVENTS GROUP BY 1,2 HAVING COUNT(*) > 1
  );
  IF (bad_count > 0) THEN RAISE bad_event; END IF;
  INSERT INTO DECISION_DELTAS
  WITH CHAIN AS (
    SELECT E.*, FALSE AS IS_NEW FROM APPLICATION_CURRENT E WHERE APPLICATION_ID IN (SELECT APPLICATION_ID FROM NEW_EVENTS)
    UNION ALL SELECT E.*, TRUE AS IS_NEW FROM NEW_EVENTS E
  ), PRIOR AS (
    SELECT *, LAG(DECISION) OVER (PARTITION BY APPLICATION_ID ORDER BY SOURCE_VERSION) AS OLD_DECISION,
      LAG(RISK_CLASS) OVER (PARTITION BY APPLICATION_ID ORDER BY SOURCE_VERSION) AS OLD_RISK_CLASS,
      LAG(CHANNEL) OVER (PARTITION BY APPLICATION_ID ORDER BY SOURCE_VERSION) AS OLD_CHANNEL
    FROM CHAIN
  ), FIELDS AS (
    SELECT EVENT_ID,APPLICATION_ID,SOURCE_VERSION,EVENT_AT,'decision' AS FIELD_NAME,OLD_DECISION AS OLD_VALUE,DECISION AS NEW_VALUE FROM PRIOR WHERE IS_NEW
    UNION ALL SELECT EVENT_ID,APPLICATION_ID,SOURCE_VERSION,EVENT_AT,'risk_class',OLD_RISK_CLASS,RISK_CLASS FROM PRIOR WHERE IS_NEW
    UNION ALL SELECT EVENT_ID,APPLICATION_ID,SOURCE_VERSION,EVENT_AT,'channel',OLD_CHANNEL,CHANNEL FROM PRIOR WHERE IS_NEW
  ) SELECT * FROM FIELDS WHERE NOT EQUAL_NULL(OLD_VALUE, NEW_VALUE);
  MERGE INTO APPLICATION_CURRENT C USING (
    SELECT * FROM NEW_EVENTS QUALIFY ROW_NUMBER() OVER (PARTITION BY APPLICATION_ID ORDER BY SOURCE_VERSION DESC) = 1
  ) N ON C.APPLICATION_ID = N.APPLICATION_ID
  WHEN MATCHED THEN UPDATE SET C.EVENT_ID=N.EVENT_ID,C.SOURCE_VERSION=N.SOURCE_VERSION,
    C.EVENT_AT=N.EVENT_AT,C.DECISION=N.DECISION,C.RISK_CLASS=N.RISK_CLASS,C.CHANNEL=N.CHANNEL
  WHEN NOT MATCHED THEN INSERT (EVENT_ID,APPLICATION_ID,SOURCE_VERSION,EVENT_AT,DECISION,RISK_CLASS,CHANNEL)
    VALUES (N.EVENT_ID,N.APPLICATION_ID,N.SOURCE_VERSION,N.EVENT_AT,N.DECISION,N.RISK_CLASS,N.CHANNEL);
  INSERT INTO PROCESSED_EVENTS SELECT * FROM NEW_EVENTS;
  COMMIT;
  RETURN 'Committed application snapshots and field deltas';
EXCEPTION
  WHEN OTHER THEN
    ROLLBACK;
    RAISE;
END;
$$;
-- Serverless task is created suspended. Resume only after granting EXECUTE MANAGED TASK.
CREATE TASK IF NOT EXISTS APPLICATION_DELTA_TASK
  USER_TASK_MANAGED_INITIAL_WAREHOUSE_SIZE = 'XSMALL'
  SCHEDULE = '5 MINUTE'
  WHEN SYSTEM$STREAM_HAS_DATA('APPLICATION_EVENT_STREAM')
  AS CALL PROCESS_APPLICATION_EVENTS();
CREATE OR REPLACE VIEW DAILY_DECISION_CHANGES AS
  SELECT TO_DATE(EVENT_AT) AS CHANGE_DATE, FIELD_NAME, OLD_VALUE, NEW_VALUE, COUNT(*) AS CHANGES
  FROM DECISION_DELTAS GROUP BY 1,2,3,4;
