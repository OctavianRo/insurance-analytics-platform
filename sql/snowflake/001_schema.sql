-- Run in a dedicated database/schema with a role granted CREATE TABLE/STREAM/PROCEDURE/TASK.
-- All DDL is additive. Snowflake primary/unique constraints are informational on standard tables.
CREATE TABLE IF NOT EXISTS APPLICATION_EVENTS (
  EVENT_ID VARCHAR NOT NULL, APPLICATION_ID VARCHAR NOT NULL, SOURCE_VERSION NUMBER NOT NULL,
  EVENT_AT TIMESTAMP_NTZ NOT NULL, DECISION VARCHAR, RISK_CLASS VARCHAR, CHANNEL VARCHAR
);
CREATE STREAM IF NOT EXISTS APPLICATION_EVENT_STREAM ON TABLE APPLICATION_EVENTS APPEND_ONLY = TRUE;
CREATE TABLE IF NOT EXISTS PROCESSED_EVENTS LIKE APPLICATION_EVENTS;
CREATE TABLE IF NOT EXISTS APPLICATION_CURRENT LIKE APPLICATION_EVENTS;
CREATE TABLE IF NOT EXISTS DECISION_DELTAS (
  EVENT_ID VARCHAR, APPLICATION_ID VARCHAR, SOURCE_VERSION NUMBER, EVENT_AT TIMESTAMP_NTZ,
  FIELD_NAME VARCHAR, OLD_VALUE VARCHAR, NEW_VALUE VARCHAR
);
CREATE TABLE IF NOT EXISTS POLICY_EXPERIENCE (
  POLICY_ID VARCHAR NOT NULL, STUDY_YEAR NUMBER NOT NULL, CLIENT VARCHAR NOT NULL,
  AGE NUMBER NOT NULL, DURATION NUMBER NOT NULL, SMOKER NUMBER NOT NULL,
  EXPOSURE FLOAT NOT NULL, DEATHS NUMBER NOT NULL, SUM_ASSURED NUMBER(20,2) NOT NULL
);
CREATE TABLE IF NOT EXISTS MORTALITY_ASSUMPTIONS (
  ASSUMPTION_VERSION VARCHAR NOT NULL, AGE NUMBER NOT NULL, SMOKER NUMBER NOT NULL,
  ANNUAL_HAZARD FLOAT NOT NULL, MULTIPLIER FLOAT NOT NULL,
  ANNUAL_IMPROVEMENT FLOAT NOT NULL, BASE_YEAR NUMBER NOT NULL
);
