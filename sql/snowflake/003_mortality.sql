-- Every assumption version is preserved. Always filter ASSUMPTION_VERSION in consuming queries.
CREATE OR REPLACE VIEW MORTALITY_STUDY AS
SELECT E.*, A.ASSUMPTION_VERSION,
  A.ANNUAL_HAZARD*A.MULTIPLIER*POWER(1-A.ANNUAL_IMPROVEMENT,E.STUDY_YEAR-A.BASE_YEAR) AS ADJUSTED_HAZARD,
  E.EXPOSURE*ADJUSTED_HAZARD AS EXPECTED_DEATHS,
  E.DEATHS*E.SUM_ASSURED AS ACTUAL_CLAIMS,
  EXPECTED_DEATHS*E.SUM_ASSURED AS EXPECTED_CLAIMS
FROM POLICY_EXPERIENCE E JOIN MORTALITY_ASSUMPTIONS A ON E.AGE=A.AGE AND E.SMOKER=A.SMOKER;
CREATE OR REPLACE VIEW MORTALITY_BENCHMARK AS
SELECT ASSUMPTION_VERSION, STUDY_YEAR, CLIENT, SUM(EXPOSURE) AS EXPOSURE,
  SUM(DEATHS) AS ACTUAL, SUM(EXPECTED_DEATHS) AS EXPECTED,
  ACTUAL/NULLIF(EXPECTED,0) AS AE_COUNT,
  SUM(ACTUAL_CLAIMS)/NULLIF(SUM(EXPECTED_CLAIMS),0) AS AE_AMOUNT
FROM MORTALITY_STUDY GROUP BY 1,2,3;
CREATE TABLE IF NOT EXISTS TERM_PROJECTIONS (
  SCENARIO_ID VARCHAR NOT NULL, PROJECTION_YEAR NUMBER NOT NULL,
  QX FLOAT NOT NULL, INTEREST FLOAT NOT NULL, BENEFIT NUMBER(20,2) NOT NULL
);
-- Conditional annual qx; annual interest may vary; end-of-year benefit payment.
-- Reject invalid inputs using 004 before reading this view.
CREATE OR REPLACE VIEW TERM_DEATH_BENEFIT_APV AS
WITH FACTORS AS (
  SELECT *, COALESCE(SUM(IFF(QX=1,1,0)) OVER (
    PARTITION BY SCENARIO_ID ORDER BY PROJECTION_YEAR ROWS BETWEEN UNBOUNDED PRECEDING AND 1 PRECEDING),0) AS PRIOR_CERTAIN_DEATH,
    COALESCE(SUM(LN(NULLIF(1-QX,0))) OVER (
    PARTITION BY SCENARIO_ID ORDER BY PROJECTION_YEAR ROWS BETWEEN UNBOUNDED PRECEDING AND 1 PRECEDING),0) AS LOG_SURVIVAL,
    SUM(LN(1+INTEREST)) OVER (PARTITION BY SCENARIO_ID ORDER BY PROJECTION_YEAR ROWS UNBOUNDED PRECEDING) AS LOG_ACCUMULATION
  FROM TERM_PROJECTIONS
)
SELECT SCENARIO_ID, SUM(IFF(PRIOR_CERTAIN_DEATH>0,0,EXP(LOG_SURVIVAL))*QX*BENEFIT*EXP(-LOG_ACCUMULATION)) AS APV
FROM FACTORS GROUP BY SCENARIO_ID;
