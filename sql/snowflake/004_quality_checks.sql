SELECT E.POLICY_ID,E.STUDY_YEAR,V.ASSUMPTION_VERSION FROM POLICY_EXPERIENCE E
  CROSS JOIN (SELECT DISTINCT ASSUMPTION_VERSION FROM MORTALITY_ASSUMPTIONS) V
  LEFT JOIN MORTALITY_ASSUMPTIONS A ON E.AGE=A.AGE AND E.SMOKER=A.SMOKER AND V.ASSUMPTION_VERSION=A.ASSUMPTION_VERSION
  WHERE A.AGE IS NULL;
